def normalize_slug(text: str) -> str:
    """Transform text into a standard alphanumeric slug."""
    s = str(text or "").strip().lower()
    s = re.sub(r"[^\w\s-]", "", s)
    return re.sub(r"[\s_]+", "-", s).strip("-")


def find_make(query: str) -> Optional[dict[str, Any]]:
    """Find canonical make by name or slug."""
    q_slug = normalize_slug(query)
    for m in CANONICAL_MAKES:
        if m["slug"] == q_slug or m["canonical_name"].lower() == query.strip().lower():
            return m
    return None


def find_model(make_dict: dict[str, Any], query: str) -> Optional[dict[str, Any]]:
    """Find canonical model inside a make dict by name or slug."""
    q_slug = normalize_slug(query)
    for mod in make_dict.get("models", []):
        if mod["slug"] == q_slug or mod["canonical_name"].lower() == query.strip().lower():
            return mod
    return None


def resolve_portal_slugs(make_input: str, model_input: str) -> dict[str, dict[str, str]]:
    """
    Resolve canonical or user-provided make/model to exact identifiers accepted by external portals.
    Returns:
    {
        "make": { "canonical": "Ford", "slug": "ford", "ebay": "Ford", "hemmings": "ford", ... },
        "model": { "canonical": "Mustang", "slug": "mustang", "ebay": "Mustang", "hemmings": "mustang", ... }
    }
    """
    clean_make = make_input.strip()
    clean_model = model_input.strip()

    make_obj = find_make(clean_make)
    make_res: dict[str, str] = {
        "canonical": make_obj["canonical_name"] if make_obj else clean_make,
        "slug": make_obj["slug"] if make_obj else normalize_slug(clean_make),
    }

    model_res: dict[str, str] = {
        "canonical": clean_model,
        "slug": normalize_slug(clean_model),
    }

    portals = ["ebay", "hemmings", "classiccars", "autotrader", "bringatrailer", "classiccom", "carscom", "cargurus", "streetside", "carsandbids"]

    if make_obj:
        for p in portals:
            make_res[p] = make_obj.get("portal_slugs", {}).get(p, make_obj["slug"])
        model_obj = find_model(make_obj, clean_model)
        if model_obj:
            model_res["canonical"] = model_obj["canonical_name"]
            model_res["slug"] = model_obj["slug"]
            for p in portals:
                model_res[p] = model_obj.get("portal_slugs", {}).get(p, model_obj["slug"])
        else:
            for p in portals:
                model_res[p] = normalize_slug(clean_model)
    else:
        for p in portals:
            make_res[p] = normalize_slug(clean_make)
            model_res[p] = normalize_slug(clean_model)

    return {"make": make_res, "model": model_res}
